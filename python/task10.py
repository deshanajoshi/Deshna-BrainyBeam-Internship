#Print Numbers

print("Numbers from 1 to 100:")
for i in range(1, 101):
    print(i)

print("\nNumbers from 100 to 1:")
for i in range(100, 0, -1):
    print(i)


print("\nNumbers from 1 to 50:")
for i in range(1, 51):
    print(i)


print("\nNumbers from 50 to 100:")
for i in range(50, 101):
    print(i)

    